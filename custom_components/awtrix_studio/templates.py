HEADER = "{#- Generated by Awtrix Studio (simple mode). -#}"

# Everything the user types ends up inside a generated template, so it is
# validated or quoted before being written there; nothing is pasted raw.
ENTITY_ID_RE = re.compile(r"^[a-z0-9_]+\.[a-z0-9_]+$")
HEX_COLOR_RE = re.compile(r"^#[0-9A-Fa-f]{6}$")
MAX_DECIMALS = 4

# What each firmware calls the keys the generated templates write. A simple
# item describes what to show; its template is written in the clock's JSON.
KEYS: dict[str, dict[str, str]] = {
    FIRMWARE_AWTRIX3: {
        "color": "color",
        "progress_color": "progressC",
        "progress_bg": "progressBC",
        "blink": "blink",
        "fade": "fade",
    },
    FIRMWARE_AWTRIX_NG: {
        "color": "textColor",
        "progress_color": "progressColor",
        "progress_bg": "progressTrackColor",
        "blink": "blinkMs",
        "fade": "fadeMs",
    },
}


# Layouts (AWTRIX NG on a TC002) count every pixel of the 52 x 16 display. The
# icon, when there is one, fills the left 16 columns: an 8 x 8 gallery icon is
# drawn at double size there (see icons). Fonts are chosen among legible ones:
# 8 pixels high for the value, 6 for the title and the two lines.
DISPLAY_WIDTH = 52
ICON_BOX = [0, 0, 16, 16]
TEXT_X = 17
TITLE_COLOR = "#969696"
# The current time of the "value and time" layout, 24-hour, rendered by Home
# Assistant (which renders a template using now() again every minute).
TIME_TEXT = 'now().strftime("%H:%M")'


def _font(options: Mapping[str, Any], key: str, fonts: Sequence[str]) -> str:
    """The font chosen for a layout, or the default (the first)."""
    font = options.get(key)
    return font if font in fonts else fonts[0]


def _keys(firmware: str) -> dict[str, str]:
    return KEYS.get(firmware, KEYS[FIRMWARE_AWTRIX3])


class InvalidSimpleOptionsError(ValueError):
    """Simple-mode options that cannot be turned into a safe template."""


def _entity_id(value: Any) -> str:
    if not isinstance(value, str) or not ENTITY_ID_RE.fullmatch(value):
        raise InvalidSimpleOptionsError(f"invalid entity id: {value!r}")
    return value


def rgb_to_hex(color: Any, default: Sequence[int]) -> str:
    """Return `#RRGGBB` for an RGB list or a hex string, else the default."""
    if isinstance(color, str):
        return (
            color.upper()
            if HEX_COLOR_RE.fullmatch(color)
            else rgb_to_hex(None, default)
        )
    try:
        channels = [int(c) for c in color] if color else []
    except (TypeError, ValueError):
        channels = []
    if len(channels) != 3:
        channels = [int(c) for c in default]
    red, green, blue = (max(0, min(255, c)) for c in channels)
    return f"#{red:02X}{green:02X}{blue:02X}"


def jinja_str(value: str) -> str:
    """Quote a value as a Jinja string literal.

    JSON string escaping is also valid Jinja string escaping: quotes,
    backslashes and control characters are escaped, so user text can never
    end the literal and be read as template code.
    """
    return json.dumps(str(value), ensure_ascii=False)


def _number(value: Any) -> float | None:
    if value is None or value == "":
        return None
    if isinstance(value, bool):
        return None
    try:
        number = float(value)
    except (TypeError, ValueError):
        return None
    return number if math.isfinite(number) else None


def app_color_mode(options: Mapping[str, Any]) -> str:
    """How a simple app picks its color (older items have no explicit mode)."""
    mode = options.get(CONF_COLOR_MODE)
    if mode in APP_COLOR_MODES:
        return mode
    if any(
        _number(options.get(key)) is not None
        for key in (CONF_THRESHOLD_1, CONF_THRESHOLD_2)
    ):
        return COLOR_STEPS
    return COLOR_FIXED


def indicator_color_mode(options: Mapping[str, Any]) -> str:
    """How a simple indicator picks its color."""
    mode = options.get(CONF_COLOR_MODE)
    return mode if mode in INDICATOR_COLOR_MODES else COLOR_STATE


def _gradient_lines(options: Mapping[str, Any]) -> list[str]:
    try:
        return jinja_lines(resolve_stops(options))
    except InvalidGradientError as err:
        raise InvalidSimpleOptionsError(str(err)) from err


def _label_color(options: Mapping[str, Any]) -> str | None:
    """The label's own color as `#RRGGBB`, when the entity shows a label.

    Without one, the label is written with the value, in the value's color.
    """
    if not str(options.get(CONF_LABEL) or "").strip():
        return None
    color = options.get(CONF_LABEL_COLOR)
    if color is None or color in ("", []):
        return None
    return rgb_to_hex(color, DEFAULT_COLOR)


# Each firmware has its own text fragments. AWTRIX 3 takes `{"t", "c"}` and
# reads the color as bare hex digits, without the "#" (a color from a
# gradient is an RGB list). AWTRIX NG takes `{"text", "color"}`, with
# "#RRGGBB" or an RGB list, as both come.
def _fragment(firmware: str, text: str, color: str) -> str:
    """A text fragment, as Jinja: `text` and `color` are expressions."""
    if firmware == FIRMWARE_AWTRIX_NG:
        return f'{{"text": {text}, "color": {color}}}'
    return f'{{"t": {text}, "c": {color}}}'


def _fragment_color(firmware: str, color: str = "color") -> str:
    """A color variable (`#RRGGBB` or an RGB list) as the firmware reads it."""
    if firmware == FIRMWARE_AWTRIX_NG:
        return color
    return (
        f'({color}[1:] if {color} is string else "%02X%02X%02X"'
        f" | format({color}[0], {color}[1], {color}[2]))"
    )


def _fixed_color(firmware: str, color: str) -> str:
    """A `#RRGGBB` color known in advance, as a fragment color literal."""
    return jinja_str(color if firmware == FIRMWARE_AWTRIX_NG else color[1:])


def app_segments(options: Mapping[str, Any]) -> list[Mapping[str, Any]]:
    """The entities of a simple app: its own first, then the next segments."""
    extra = options.get(CONF_SEGMENTS) or []
    return [options, *(s for s in extra if isinstance(s, Mapping))]


def build_app_template(
    options: Mapping[str, Any], firmware: str = FIRMWARE_AWTRIX3
) -> str:
    """Template for a simple app: entities shown as text, with an icon."""
    if firmware == FIRMWARE_AWTRIX_NG and options.get(CONF_LAYOUT) in LAYOUTS:
        return _build_layout_template(options)
    if len(app_segments(options)) > 1:
        return _build_line_template(options, firmware)
    keys = _keys(firmware)
    entity = _entity_id(options.get(CONF_ENTITY_ID))
    hide_zero = options.get(CONF_HIDE_WHEN_ZERO, False)

    lines = [
        HEADER,
        f"{{%- set raw = states({jinja_str(entity)}) -%}}",
        "{%- set num = raw | float if raw | is_number else none -%}",
        "{%- if raw in ['unknown', 'unavailable', ''] -%}",
        "[]",
    ]
    if hide_zero:
        lines += ["{%- elif num is not none and num == 0 -%}", "[]"]
    lines.append("{%- else -%}")
    lines += _text_lines(options)
    label_color = _label_color(options)
    if label_color is None:
        lines += _payload_lines(options, entity, keys, "text")
        return "\n".join(lines)
    # A label in its own color: the text is sent as two fragments, and each
    # brings its color.
    parts = (
        f"[{_fragment(firmware, 'label', _fixed_color(firmware, label_color))},"
        f" {_fragment(firmware, 'text', _fragment_color(firmware))}]"
    )
    lines += _payload_lines(options, entity, keys, parts, with_color=False)
    return "\n".join(lines)


def _build_line_template(options: Mapping[str, Any], firmware: str) -> str:
    """Several entities on one line, each in its own color.

    An entity without a value (or at 0, when asked) leaves the line; the app
    is hidden when none is left.
    """
    keys = _keys(firmware)
    segments = app_segments(options)
    separator = options.get(CONF_SEPARATOR)
    if not isinstance(separator, str):
        separator = DEFAULT_SEPARATOR
    gap = f'({jinja_str(separator)} if parts else "")'
    lines = [HEADER, "{%- set parts = [] -%}"]
    for number, segment in enumerate(segments, 1):
        entity = _entity_id(segment.get(CONF_ENTITY_ID))
        shown = "raw not in ['unknown', 'unavailable', '']"
        if segment.get(CONF_HIDE_WHEN_ZERO, False):
            shown += " and not (num is not none and num == 0)"
        value = _fragment(firmware, "text", _fragment_color(firmware))
        if (label_color := _label_color(segment)) is None:
            added = _fragment(firmware, f"{gap} ~ text", _fragment_color(firmware))
        else:
            # The label in its own color, then the value in the entity's.
            label = _fragment(
                firmware, f"{gap} ~ label", _fixed_color(firmware, label_color)
            )
            added = f"{label}, {value}"
        lines += [
            f"{{#- Entity {number}: {entity} -#}}",
            f"{{%- set raw = states({jinja_str(entity)}) -%}}",
            "{%- set num = raw | float if raw | is_number else none -%}",
            f"{{%- if {shown} -%}}",
            *_text_lines(segment),
            "{%- if not parts -%}{%- set first = color -%}{%- endif -%}",
            f"{{%- set parts = parts + [{added}] -%}}",
            "{%- endif -%}",
        ]
    lines += ["{%- if not parts -%}", "[]", "{%- else -%}"]
    if options.get(CONF_PROGRESS):
        # The first color paints the progress bar, as with one entity.
        lines.append("{%- set color = first -%}")
    # No color for the whole text: each fragment brings its own. On NG a
    # rainbow or gradient text style still wins, through `textColor:
    # "palette"` (see display).
    lines += _payload_lines(
        options, segments[0][CONF_ENTITY_ID], keys, "parts", with_color=False
    )
    return "\n".join(lines)


def _box(x: int, y: int, width: int, height: int) -> str:
    return f"[{x}, {y}, {width}, {height}]"


def _text_region(
    region_id: str, box: str, text: str, font: str, color: str, *, extra: str = ""
) -> str:
    """A text region, as Jinja: `text` and `color` are expressions."""
    return (
        f'{{"id": "{region_id}", "box": {box}, "text": {text},'
        f' "font": "{font}", "color": {color}{extra}}}'
    )


def _icon_regions(icon: str) -> tuple[int, int, str]:
    """Where the text starts, how wide it is, and the regions of the icon.

    The icon sits on the left when there is one; the regions are a Jinja list.
    """
    x = TEXT_X if icon else 0
    regions = (
        f'[{{"id": "icon", "box": {ICON_BOX}, "icon": {jinja_str(icon)}}}]'
        if icon
        else "[]"
    )
    return x, DISPLAY_WIDTH - x, regions


def _entity_block(
    number: int, segment: Mapping[str, Any], assign: str, init: Sequence[str] = ()
) -> list[str]:
    """Lines reading the entity of a line, then running `assign` when it is shown.

    `init` runs first, before the entity is read; `assign` can use the `text`,
    `label` and `color` that the lines of the text define.
    """
    entity = _entity_id(segment.get(CONF_ENTITY_ID))
    shown = "raw not in ['unknown', 'unavailable', '']"
    if segment.get(CONF_HIDE_WHEN_ZERO, False):
        shown += " and not (num is not none and num == 0)"
    return [
        f"{{#- Line {number}: {entity} -#}}",
        *init,
        f"{{%- set raw = states({jinja_str(entity)}) -%}}",
        "{%- set num = raw | float if raw | is_number else none -%}",
        f"{{%- if {shown} -%}}",
        *_text_lines(segment),
        assign,
        "{%- endif -%}",
    ]


def _build_layout_template(options: Mapping[str, Any]) -> str:
    """An app drawn on the whole display of a TC002, in boxes (AWTRIX NG).

    The icon sits on the left when there is one. Then, by layout: the value
    alone, a title above the value, the value above a progress bar, two
    entities, one per line, or the current time above the value.
    """
    layout = options[CONF_LAYOUT]
    icon = str(options.get(CONF_ICON) or "").strip()
    x, width, regions = _icon_regions(icon)
    lines = [HEADER]
    if layout == LAYOUT_TWO_LINES:
        return "\n".join(lines + _two_lines(options, regions, x, width))

    entity = _entity_id(options.get(CONF_ENTITY_ID))
    title = str(options.get(CONF_LABEL) or "").strip()
    lines += [
        f"{{%- set raw = states({jinja_str(entity)}) -%}}",
        "{%- set num = raw | float if raw | is_number else none -%}",
        "{%- if raw in ['unknown', 'unavailable', ''] -%}",
        "[]",
    ]
    if options.get(CONF_HIDE_WHEN_ZERO, False):
        lines += ["{%- elif num is not none and num == 0 -%}", "[]"]
    lines.append("{%- else -%}")
    lines += _text_lines(options, with_label=layout != LAYOUT_TITLE_VALUE)

    value_box = _box(x, 0, width, 16)
    label_color = _label_color(options)
    if layout == LAYOUT_TITLE_VALUE and title:
        title_region = _text_region(
            "title",
            _box(x, 0, width, 7),
            jinja_str(title),
            _font(options, CONF_TEXT_FONT, TEXT_FONTS),
            jinja_str(label_color or TITLE_COLOR),
        )
        regions = f"{regions} + [{title_region}]"
        value_box = _box(x, 8, width, 8)
    elif layout == LAYOUT_VALUE_TIME:
        # The time on top, small, like a title; the value below.
        time_region = _text_region(
            "time",
            _box(x, 0, width, 7),
            TIME_TEXT,
            _font(options, CONF_TEXT_FONT, TEXT_FONTS),
            jinja_str(TITLE_COLOR),
        )
        regions = f"{regions} + [{time_region}]"
        value_box = _box(x, 8, width, 8)
    elif layout == LAYOUT_VALUE_BAR:
        value_box = _box(x, 0, width, 11)
    value_font = _font(options, CONF_VALUE_FONT, VALUE_FONTS)
    # The title layout shows the label apart, above: the value is alone.
    text = "text" if layout == LAYOUT_TITLE_VALUE else _layout_text(options)
    value = _text_region("value", value_box, text, value_font, "color")
    lines.append(f"{{%- set regions = {regions} + [{value}] -%}}")
    if layout == LAYOUT_VALUE_BAR:
        lines += _bar_lines(options, entity, _box(x, 12, width, 3))
    lines += [
        '{{ {"layout": {"version": 1, "regions": regions}} | tojson }}',
        "{%- endif -%}",
    ]
    return "\n".join(lines)


def _layout_text(options: Mapping[str, Any]) -> str:
    """The text of a layout line: a label in its own color makes it fragments.

    A fragment without a color takes the region's, the value's color.
    """
    label_color = _label_color(options)
    if label_color is None:
        return "text"
    return f'[{{"text": label, "color": {jinja_str(label_color)}}}, {{"text": text}}]'


def _two_lines(
    options: Mapping[str, Any], regions: str, x: int, width: int
) -> list[str]:
    """Two entities, one per line; one left alone takes the whole height."""
    lines = ["{%- set parts = [] -%}"]
    for number, segment in enumerate(app_segments(options)[:2], 1):
        assign = (
            f'{{%- set parts = parts + [{{"t": {_layout_text(segment)},'
            ' "c": color}] -%}'
        )
        lines += _entity_block(number, segment, assign)
    value_font = _font(options, CONF_VALUE_FONT, VALUE_FONTS)
    line_font = _font(options, CONF_TEXT_FONT, TEXT_FONTS)
    alone = _text_region(
        "line1", _box(x, 0, width, 16), "parts[0].t", value_font, "parts[0].c"
    )
    start = ', "align": "start"'
    first = _text_region(
        "line1",
        _box(x, 0, width, 8),
        "parts[0].t",
        line_font,
        "parts[0].c",
        extra=start,
    )
    second = _text_region(
        "line2",
        _box(x, 8, width, 8),
        "parts[1].t",
        line_font,
        "parts[1].c",
        extra=start,
    )
    return [
        *lines,
        "{%- if not parts -%}",
        "[]",
        "{%- elif parts | length == 1 -%}",
        f'{{{{ {{"layout": {{"version": 1, "regions": {regions} + [{alone}]}}}}'
        " | tojson }}",
        "{%- else -%}",
        f'{{{{ {{"layout": {{"version": 1, "regions": {regions}'
        f" + [{first}, {second}]}}}} | tojson }}}}",
        "{%- endif -%}",
    ]


def _bar_lines(options: Mapping[str, Any], entity: str, box: str) -> list[str]:
    """Lines adding a progress bar region, from a value between min and max."""
    source = _entity_id(options.get(CONF_PROGRESS_ENTITY) or entity)
    low, high = _progress_range(options)
    bar = (
        jinja_str(rgb_to_hex(options[CONF_PROGRESS_COLOR], DEFAULT_COLOR))
        if options.get(CONF_PROGRESS_COLOR)
        else "color"
    )
    track = jinja_str(rgb_to_hex(options.get(CONF_PROGRESS_BG), DEFAULT_PROGRESS_BG))
    return [
        "{#- Progress bar: the value between min and max, as 0 to 100. -#}",
        f"{{%- set p = states({jinja_str(source)}) -%}}",
        "{%- if p | is_number -%}",
        f"{{%- set ratio = (p | float - {low!r}) / {high - low!r} -%}}",
        '{%- set regions = regions + [{"id": "bar", "box": ' + box + ","
        ' "progress": ([[ratio * 100, 0] | max, 100] | min) | round(0) | int,'
        f' "color": {bar}, "trackColor": {track}}}] -%}}',
        "{%- endif -%}",
    ]


def _progress_range(options: Mapping[str, Any]) -> tuple[float, float]:
    low = _number(options.get(CONF_PROGRESS_MIN))
    high = _number(options.get(CONF_PROGRESS_MAX))
    low = DEFAULT_PROGRESS_MIN if low is None else low
    high = DEFAULT_PROGRESS_MAX if high is None else high
    if high <= low:
        raise InvalidSimpleOptionsError("the progress maximum must exceed the minimum")
    return low, high


def _text_lines(options: Mapping[str, Any], *, with_label: bool = True) -> list[str]:
    """Lines setting `text` and `color` for one entity, from `raw` and `num`."""
    entity = _entity_id(options.get(CONF_ENTITY_ID))
    label = str(options.get(CONF_LABEL) or "").strip()
    color = rgb_to_hex(options.get(CONF_COLOR), DEFAULT_COLOR)
    decimals = options.get(CONF_DECIMALS)
    show_unit = options.get(CONF_SHOW_UNIT, True)

    lines: list[str] = []
    if decimals is not None and decimals != "":
        decimals = max(0, min(MAX_DECIMALS, int(decimals)))
    if decimals is None or decimals == "":
        lines.append("{%- set value = raw -%}")
    elif decimals == 0:
        lines.append(
            "{%- set value = num | round(0) | int if num is not none else raw -%}"
        )
    else:
        rounded = f"num | round({int(decimals)})"
        lines.append(f"{{%- set value = {rounded} if num is not none else raw -%}}")

    # A label in its own color is kept apart, as `label`, to be sent as a
    # fragment of its own; otherwise it starts the text.
    apart = with_label and _label_color(options) is not None
    text = "value | string"
    if label and with_label and not apart:
        text = f"{jinja_str(label + ' ')} ~ value"
    if apart:
        lines.append(f"{{%- set label = {jinja_str(label + ' ')} -%}}")
    if show_unit:
        custom_unit = str(options.get(CONF_UNIT) or "").strip()
        unit = (
            jinja_str(custom_unit)
            if custom_unit
            else f"state_attr({jinja_str(entity)}, 'unit_of_measurement') or ''"
        )
        lines += [
            f"{{%- set unit = {unit} -%}}",
            # Like Home Assistant: no space before °C, °F or %.
            "{%- set sep = '' if unit[:1] in ['', '°', '%'] else ' ' -%}",
        ]
        text += " ~ sep ~ unit"
    lines.append(f"{{%- set text = {text} -%}}")

    lines.append(f"{{%- set color = {jinja_str(color)} -%}}")
    lines += _color_lines(options)
    return lines


def _payload_lines(
    options: Mapping[str, Any],
    entity: str,
    keys: Mapping[str, str],
    text: str,
    *,
    with_color: bool = True,
) -> list[str]:
    """Lines writing the page, with its icon and progress bar; ends the `if`."""
    icon = str(options.get(CONF_ICON) or "").strip()
    payload = f'{{"text": {text}'
    if with_color:
        payload += f', "{keys["color"]}": color'
    if icon:
        payload += f', "icon": {jinja_str(icon)}'
    payload += "}"
    if not options.get(CONF_PROGRESS):
        return [f"{{{{ {payload} | tojson }}}}", "{%- endif -%}"]
    return [
        f"{{%- set page = {payload} -%}}",
        *_progress_lines(options, entity, keys),
        "{{ page | tojson }}",
        "{%- endif -%}",
    ]


def _color_lines(options: Mapping[str, Any]) -> list[str]:
    """Lines changing `color` by steps or along a gradient."""
    lines: list[str] = []
    color_mode = app_color_mode(options)
    if color_mode == COLOR_GRADIENT:
        lines += [
            "{%- if num is not none -%}",
            *_gradient_lines(options),
            "{%- endif -%}",
        ]
    for threshold_key, color_key in (
        (CONF_THRESHOLD_1, CONF_COLOR_1),
        (CONF_THRESHOLD_2, CONF_COLOR_2),
    ):
        if color_mode != COLOR_STEPS:
            break
        threshold = _number(options.get(threshold_key))
        if threshold is None:
            continue
        above = rgb_to_hex(options.get(color_key), DEFAULT_COLOR)
        lines.append(
            f"{{%- if num is not none and num > {threshold!r} -%}}"
            f"{{%- set color = {jinja_str(above)} -%}}{{%- endif -%}}"
        )
    return lines


def _progress_lines(
    options: Mapping[str, Any], entity: str, keys: Mapping[str, str]
) -> list[str]:
    """Lines adding a progress bar to `page`, from a value between min and max."""
    source = options.get(CONF_PROGRESS_ENTITY) or entity
    source = _entity_id(source)
    low, high = _progress_range(options)
    bar = (
        jinja_str(rgb_to_hex(options[CONF_PROGRESS_COLOR], DEFAULT_COLOR))
        if options.get(CONF_PROGRESS_COLOR)
        else "color"
    )
    background = jinja_str(
        rgb_to_hex(options.get(CONF_PROGRESS_BG), DEFAULT_PROGRESS_BG)
    )
    return [
        "{#- Progress bar: the value between min and max, as 0 to 100. -#}",
        f"{{%- set p = states({jinja_str(source)}) -%}}",
        "{%- if p | is_number -%}",
        f"{{%- set ratio = (p | float - {low!r}) / {high - low!r} -%}}",
        "{%- set page = dict(page, progress=([[ratio * 100, 0] | max, 100] | min)"
        f" | round(0) | int, {keys['progress_color']}={bar},"
        f" {keys['progress_bg']}={background}) -%}}",
        "{%- endif -%}",
    ]


def build_indicator_template(
    options: Mapping[str, Any], firmware: str = FIRMWARE_AWTRIX3
) -> str:
    """Template for a simple indicator: lit while an entity is in a state."""
    keys = _keys(firmware)
    entity = _entity_id(options.get(CONF_ENTITY_ID))
    active = str(options.get(CONF_ACTIVE_STATE) or DEFAULT_ACTIVE_STATE).strip()
    color = rgb_to_hex(options.get(CONF_COLOR), DEFAULT_INDICATOR_COLOR)
    effect = options.get(CONF_EFFECT, EFFECT_NONE)
    if effect not in EFFECTS:
        effect = EFFECT_NONE
    interval = int(options.get(CONF_EFFECT_INTERVAL) or DEFAULT_EFFECT_INTERVAL)
    interval = max(50, min(60000, interval))

    extra = f', "{keys[effect]}": {interval}' if effect != EFFECT_NONE else ""

    if indicator_color_mode(options) == COLOR_GRADIENT:
        return "\n".join(
            [
                HEADER,
                f"{{%- set raw = states({jinja_str(entity)}) -%}}",
                "{%- if raw | is_number -%}",
                "{%- set num = raw | float -%}",
                *_gradient_lines(options),
                f'{{{{ {{"color": color{extra}}} | tojson }}}}',
                "{%- else -%}",
                "{}",
                "{%- endif -%}",
            ]
        )

    payload = f'{{"color": {jinja_str(color)}{extra}}}'
    return "\n".join(
        [
            HEADER,
            f"{{%- if is_state({jinja_str(entity)}, {jinja_str(active)}) -%}}",
            f"{{{{ {payload} | tojson }}}}",
            "{%- else -%}",
            "{}",
            "{%- endif -%}",
        ]
    )


# ------------------------------------------------- notification lines


def notification_font(layout: str, index: int, font: Any) -> str:
    """The font of a line, or its layout's default.

    A title is 7 pixels high: only the small fonts fit there. The first line of
    a lone line, and the value under a title, are 8 pixels high.
    """
    if layout == LAYOUT_TITLE_VALUE and index == 0:
        return font if font in TEXT_FONTS else TEXT_FONTS[0]
    default = TEXT_FONTS[0] if layout == LAYOUT_TWO_LINES else VALUE_FONTS[0]
    return font if font in (*VALUE_FONTS, *TEXT_FONTS) else default


def _line_lines(number: int, line: Mapping[str, Any]) -> list[str]:
    """Lines setting `line<number>` to its text and color, or to none."""
    name = f"line{number}"
    entity = str(line.get(CONF_ENTITY_ID) or "").strip()
    label = str(line.get(CONF_LABEL) or "").strip()
    if not entity:
        color = rgb_to_hex(line.get(CONF_COLOR), DEFAULT_COLOR)
        if not label:
            return [f"{{%- set {name} = none -%}}"]
        return [
            f'{{%- set {name} = {{"t": {jinja_str(label)}, "c": {jinja_str(color)}}}'
            " -%}"
        ]
    return _entity_block(
        number,
        line,
        f'{{%- set {name} = {{"t": text, "c": color}} -%}}',
        init=[f"{{%- set {name} = none -%}}"],
    )


def build_lines_template(options: Mapping[str, Any]) -> str:
    """Template for a notification: one or two lines, each a text and/or an entity.

    Without a layout the lines are written in one text. A layout (on a TC002)
    draws each line in its own place and font. For AWTRIX NG only.
    """
    layout = options.get(CONF_LAYOUT) or ""
    lines_options = app_segments(options)
    keys = _keys(FIRMWARE_AWTRIX_NG)
    icon = str(options.get(CONF_ICON) or "").strip()
    out = [HEADER]
    for number, line in enumerate(lines_options, 1):
        out += _line_lines(number, line)
    names = ", ".join(f"line{n}" for n in range(1, len(lines_options) + 1))
    out += [
        f"{{%- set shown = [{names}] | reject('none') | list -%}}",
        "{%- if not shown -%}",
        "[]",
        "{%- else -%}",
    ]
    if layout not in NOTIFICATION_LAYOUTS:
        text = 'shown | map(attribute="t") | join(" ")'
        page = f'{{"text": {text}, "{keys["color"]}": shown[0].c'
        if icon:
            page += f', "icon": {jinja_str(icon)}'
        return "\n".join([*out, f"{{{{ {page}}} | tojson }}}}", "{%- endif -%}"])

    x, width, regions = _icon_regions(icon)
    out.append(f"{{%- set regions = {regions} -%}}")
    if layout == LAYOUT_LINE:
        boxes = [_box(x, 0, width, 16)]
    elif layout == LAYOUT_TWO_LINES:
        boxes = [_box(x, 0, width, 8), _box(x, 8, width, 8)]
    else:
        boxes = [_box(x, 0, width, 7), _box(x, 8, width, 8)]
    for number, box in enumerate(boxes, 1):
        if number > len(lines_options):
            break
        line = lines_options[number - 1]
        font = notification_font(layout, number - 1, line.get(CONF_FONT))
        # Centered is the clock's own default.
        align = line.get(CONF_ALIGN)
        extra = f', "align": "{align}"' if align in ("start", "end") else ""
        region = _text_region(
            f"line{number}",
            box,
            f"line{number}.t",
            font,
            f"line{number}.c",
            extra=extra,
        )
        out += [
            f"{{%- if line{number} -%}}",
            f"{{%- set regions = regions + [{region}] -%}}",
            "{%- endif -%}",
        ]
    out += [
        '{{ {"layout": {"version": 1, "regions": regions}} | tojson }}',
        "{%- endif -%}",
    ]
    return "\n".join(out)
